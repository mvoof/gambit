//! Generates the TypeScript contract from `gb-model`: `npm run contract`.

use std::path::PathBuf;

use gb_model::{
    AppSettings, ArchiveStats, CatalogEntry, EngineInfo, EngineInstallProgress, Evaluation,
    GameReview, GameSummary, GameView, NewGameOptions, PieceSetView, ReplayGame, SheetColumnOrder,
    EVENT_ENGINE_INSTALL, EVENT_EVALUATION, EVENT_GAME_REVIEW, EVENT_GAME_UPDATED,
};
use specta::Types;
use specta_typescript::Typescript;

const BINDINGS_PATH: &str = "../src/shared/contracts/generated/bindings.ts";
const HEADER: &str = "// Generated by src-tauri/src/bindings.rs. Never edit by hand.";

fn collect_types() -> Types {
    Types::default()
        .register::<AppSettings>()
        .register::<ArchiveStats>()
        .register::<EngineInfo>()
        .register::<CatalogEntry>()
        .register::<EngineInstallProgress>()
        .register::<Evaluation>()
        .register::<GameReview>()
        .register::<GameSummary>()
        .register::<GameView>()
        .register::<NewGameOptions>()
        .register::<PieceSetView>()
        .register::<ReplayGame>()
        .register::<SheetColumnOrder>()
}

fn event_constants() -> String {
    format!(
        "export const EVENT_GAME_UPDATED = '{EVENT_GAME_UPDATED}';\n\
         export const EVENT_EVALUATION = '{EVENT_EVALUATION}';\n\
         export const EVENT_ENGINE_INSTALL = '{EVENT_ENGINE_INSTALL}';\n\
         export const EVENT_GAME_REVIEW = '{EVENT_GAME_REVIEW}';\n"
    )
}

pub fn export() -> Result<(), String> {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);

    Typescript::default()
        .header(HEADER)
        .with_raw(event_constants())
        .export_to(path, &collect_types(), specta_serde::Format)
        .map_err(|error| error.to_string())
}

